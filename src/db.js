'use strict';

// Postgres version of the database layer (works with Supabase's free tier).
// Connection string comes from DATABASE_URL.

const { Pool, types } = require('pg');

// COUNT(*) comes back as bigint (a string by default); make it a number.
types.setTypeParser(20, (v) => Number(v));

const SCHEMA = `
CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_login TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_admins_email ON admins (lower(email));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS spaces (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  floor INTEGER,
  size_sqm DOUBLE PRECISION,
  monthly_rate DOUBLE PRECISION,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available','reserved','occupied')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS space_photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  space_id INTEGER NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
  mime TEXT NOT NULL,
  data BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no TEXT UNIQUE,
  space_id INTEGER REFERENCES spaces(id) ON DELETE SET NULL,
  space_name TEXT NOT NULL,
  business_name TEXT NOT NULL,
  business_description TEXT NOT NULL DEFAULT '',
  business_type TEXT NOT NULL DEFAULT '',
  target_start_date TEXT,
  contact_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined')),
  decision_note TEXT NOT NULL DEFAULT '',
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at TIMESTAMPTZ,
  decided_by INTEGER REFERENCES admins(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_space ON requests(space_id);

CREATE TABLE IF NOT EXISTS request_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  "at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_events_request ON request_events(request_id);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Supabase exposes tables through its public API. This app talks to Postgres
-- directly from the server, so lock every table away from that API.
ALTER TABLE admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE spaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE space_photos ENABLE ROW LEVEL SECURITY;
ALTER TABLE requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE request_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
`;

// Everything the client has not decided yet lives here, so the admin can
// fill it in without touching code.
const DEFAULT_SETTINGS = {
  address: 'Don Rufino Alonzo Sr. St., Brgy. Poblacion 5, Cotabato City 9600',
  contact_phone: '',
  contact_email: '',
  office_hours: '',
  directions_url: '',
  show_rates: '0'
};

// Small helpers shared by the pool and by a checked-out transaction client.
function wrap(runner) {
  return {
    query: (text, params) => runner.query(text, params),
    async all(text, params) { return (await runner.query(text, params)).rows; },
    async one(text, params) { return (await runner.query(text, params)).rows[0] || null; }
  };
}

async function openDb(connectionString) {
  const url = connectionString || process.env.DATABASE_URL;
  if (!url) throw new Error('DATABASE_URL is not set. Add your Supabase connection string to .env');
  const local = /@(localhost|127\.0\.0\.1)/.test(url);
  const pool = new Pool({
    connectionString: url,
    max: 5,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 10000,
    ssl: local ? false : { rejectUnauthorized: false }
  });
  pool.on('error', (err) => console.error('Idle database client error:', err.message));

  const db = {
    ...wrap(pool),
    // Run fn(tx) inside a transaction; commits on success, rolls back on any throw.
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(wrap(client));
        await client.query('COMMIT');
        return out;
      } catch (err) {
        try { await client.query('ROLLBACK'); } catch { /* connection already gone */ }
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end()
  };

  await pool.query(SCHEMA);
  for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
    await pool.query('INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO NOTHING', [k, v]);
  }
  return db;
}

async function getSettings(db) {
  const out = { ...DEFAULT_SETTINGS };
  for (const row of await db.all('SELECT key, value FROM settings')) {
    if (row.key in DEFAULT_SETTINGS) out[row.key] = row.value;
  }
  return out;
}

async function setSettings(db, patch) {
  await db.tx(async (tx) => {
    for (const [k, v] of Object.entries(patch)) {
      if (k in DEFAULT_SETTINGS) {
        await tx.query(
          'INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value',
          [k, String(v)]
        );
      }
    }
  });
}

// Matches the three cards in the Figma design. Details are left empty on
// purpose: the client has not provided sizes, rates or photos yet.
async function seedSampleSpaces(db) {
  const { n } = await db.one('SELECT COUNT(*) AS n FROM spaces');
  if (n > 0 || process.env.SEED_SAMPLE === '0') return false;
  await db.tx(async (tx) => {
    const insert = 'INSERT INTO spaces (name, floor, status, sort_order) VALUES ($1, $2, $3, $4)';
    await tx.query(insert, ['Unit 1', null, 'available', 1]);
    await tx.query(insert, ['Unit 2', null, 'available', 2]);
    await tx.query(insert, ['Unit 3', null, 'reserved', 3]);
  });
  return true;
}

module.exports = { openDb, getSettings, setSettings, seedSampleSpaces, DEFAULT_SETTINGS };
